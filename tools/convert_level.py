"""Convert one Black Tiger level from the ROM set into Amiga AGA data.

usage: python3 tools/convert_level.py ROMS LEVEL(1-8) OUTDIR

Writes into OUTDIR:
  level.pal    256 x ULONG $00RRGGBB  (indices 0..127 background, 128..255 reserved)
  level.tiles  N x 16x16x8bpp tiles, planar: plane-major (8 planes x 16 rows x 1 word)
  level.map    MAP_W*MAP_H UWORD tile numbers, row-major
  level.i      assembler constants
"""
import os
import sys

import bt_level
import bt_rom

BG_COLOURS = 128   # palette slots given to the background; the rest is for sprites


def convert(roms, level, out):
    level -= 1
    os.makedirs(out, exist_ok=True)
    R = bt_rom.load_roms(roms)
    rom = R["maincpu"]
    tiles = bt_rom.decode_16x16(R["tiles"])
    pal = bt_level.level_palette(rom, level)
    bg = bt_level.level_map(rom, level)
    layout = bt_level.guess_layout(bg, tiles)
    if layout != 0:
        raise SystemExit("level %d uses the 128x64 layout - not supported by the viewer yet" % (level + 1))
    map_w, map_h = 64, 128

    # Background pen 15 is transparent on the back layer: arcade shows palette entry 1023 there.
    backdrop = pal[1023]
    colours = [backdrop]
    index = {backdrop: 0}

    def colour_index(rgb):
        if rgb not in index:
            index[rgb] = len(colours)
            colours.append(rgb)
        return index[rgb]

    tile_ids = {}
    tile_data = []
    cells = []
    for col, row, code, color, flip in bt_level.map_cells(bg, layout):
        key = (code, color, flip)
        if key not in tile_ids:
            src = tiles[code]
            px = []
            for y in range(16):
                for x in range(16):
                    v = src[y * 16 + (15 - x if flip else x)]
                    px.append(0 if v == 15 else colour_index(pal[color * 16 + v]))
            tile_ids[key] = len(tile_data)
            tile_data.append(px)
        cells.append(tile_ids[key])
    if len(colours) > BG_COLOURS:
        raise SystemExit("level %d needs %d background colours (> %d)" % (level + 1, len(colours), BG_COLOURS))

    with open(os.path.join(out, "level.pal"), "wb") as f:
        for i in range(256):
            r, g, b = colours[i] if i < len(colours) else (0, 0, 0)
            f.write(bytes((0, r, g, b)))

    with open(os.path.join(out, "level.tiles"), "wb") as f:
        for px in tile_data:
            for plane in range(8):
                for y in range(16):
                    w = 0
                    for x in range(16):
                        w = w << 1 | (px[y * 16 + x] >> plane & 1)
                    f.write(w.to_bytes(2, "big"))

    with open(os.path.join(out, "level.map"), "wb") as f:
        for t in cells:
            f.write(t.to_bytes(2, "big"))

    with open(os.path.join(out, "level.i"), "w") as f:
        f.write("; generated by tools/convert_level.py - level %d\n" % (level + 1))
        f.write("MAP_W\t\tequ\t%d\nMAP_H\t\tequ\t%d\nTILE_COUNT\tequ\t%d\nBG_COLOURS\tequ\t%d\n" %
                (map_w, map_h, len(tile_data), len(colours)))

    print("level %d: %d tiles (%d KB), %d background colours" %
          (level + 1, len(tile_data), len(tile_data) * 256 // 1024, len(colours)))


if __name__ == "__main__":
    convert(sys.argv[1], int(sys.argv[2]), sys.argv[3])
