"""analysis/bank_reads_raw.txt (tools/mame/bank_reads.lua) -> data/bank_reads.txt

MAME reports the program counter after the opcode bytes already fetched; map
it back to the start of the instruction using the code map. Merges with the
existing list.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import bt_rom  # noqa: E402
from z80 import codemap  # noqa: E402


def main():
    rom = bt_rom.load_roms(os.path.join(ROOT, "roms", "blktiger.zip"))["maincpu"]
    cm = codemap.build(rom, os.path.join(ROOT, "data", "code_entries.txt"))
    out_path = os.path.join(ROOT, "data", "bank_reads.txt")
    sites = set()
    if os.path.exists(out_path):
        for line in open(out_path):
            f = line.split()
            if f and not line.startswith("#"):
                sites.add((None if f[0] == "ff" else int(f[0], 16), int(f[1], 16)))
    miss = []
    for line in open(os.path.join(ROOT, "analysis", "bank_reads_raw.txt")):
        f = line.split()
        if len(f) < 3 or f[0] != "R":
            continue
        pc, bank = int(f[1], 16), int(f[2], 16)
        for back in range(1, 5):
            key = codemap.loc(bank, pc - back)
            ins = cm.insns.get(key)
            if ins and pc - back < pc <= pc - back + ins.length:
                sites.add(key)
                break
        else:
            miss.append(line.strip())
    with open(out_path, "w") as fh:
        fh.write("# Z80 instructions seen reading data from the banked ROM window: code bank\n"
                 "# (ff = fixed ROM), address. Generated by tools/mame/bank_reads.sh.\n")
        for b, a in sorted(sites, key=lambda k: (-1 if k[0] is None else k[0], k[1])):
            fh.write("%s %04x  %s\n" % ("ff" if b is None else "%02x" % b, a, cm.insns[(b, a)].text))
    print("%d sites; %d reads not mapped to known code %s" % (len(sites), len(miss), miss[:5]))


if __name__ == "__main__":
    main()
